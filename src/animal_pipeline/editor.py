def digest_statements(text: str) -> str:
    import hashlib
    return hashlib.sha256(text.encode()).hexdigest()


def _ffmpeg(args: list[str]) -> None:
    result = subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", *args],
                            capture_output=True, text=True, timeout=1800)
    if result.returncode:
        raise RuntimeError(f"ffmpeg failed: {result.stderr[-800:]}")


def _encoder() -> str:
    encoder = settings()["render"]["encoder"]
    result = subprocess.run(["ffmpeg", "-hide_banner", "-encoders"],
                            capture_output=True, text=True, timeout=30)
    if encoder not in result.stdout:
        raise RuntimeError(f"required encoder unavailable: {encoder}")
    return encoder


def plan_min_duration(plan: dict, cfg: dict) -> float:
    """Lower render bound for a validated plan.

    save_plan already enforced the footage budget and recorded the selected
    profile inside the immutable plan, so a recorded MICRO/STANDARD profile
    is a legitimate duration exception — not an operator override.
    """
    if plan.get("runtime_exception"):
        return float(cfg["exception_min_duration_s"])
    profile = (plan.get("footage_profile") or {}).get("profile")
    if profile == "MICRO":
        return float(cfg["exception_min_duration_s"])
    if profile == "STANDARD":
        return 30.0
    return float(cfg["min_duration_s"])


def audio_timing_ok(video_duration: float, audio_duration: float) -> bool:
    return video_duration > 0 and 0.92 * video_duration <= audio_duration <= video_duration + 0.2


def loudness_lufs(path: Path) -> float:
    result = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(path),
                             "-af", "ebur128", "-f", "null", "-"],
                            capture_output=True, text=True, timeout=600)
    summary = result.stderr.rsplit("Summary:", 1)[-1]
    match = re.search(r"I:\s*(-?\d+(?:\.\d+)?)\s*LUFS", summary)
    if result.returncode or not match:
        raise RuntimeError("could not measure integrated loudness")
    return float(match.group(1))


def narration_gain(path: Path) -> float:
    cfg = settings()
    measured = loudness_lufs(path)
    gain = cfg["render"]["loudness_target"] - measured
    if abs(gain) > cfg["voice"]["max_gain_db"]:
        raise RuntimeError(f"narration at {measured:.1f} LUFS needs unsafe {gain:.1f} dB gain")
    return gain


def compose(conn: sqlite3.Connection, plan_id: str, narration: Path | None = None, *,
            simulation: bool = False) -> dict:
    row = conn.execute("SELECT * FROM plans WHERE id=?", (plan_id,)).fetchone()
    if not row:
        raise ValueError("unknown plan")
    plan = json.loads(row["content"])
    errors = validate_segments(conn, row["topic_id"], plan["segments"])
    if simulation and not narration:
        errors.append("test simulation requires test audio")
    if not simulation and narration is not None:
        errors.append("production narration must be generated by the approved voice")
    clips = []
    topic = conn.execute("SELECT * FROM topics WHERE id=?", (row["topic_id"],)).fetchone()
    for shot in plan["segments"]:
        asset = conn.execute("SELECT * FROM assets WHERE id=?", (shot["asset_id"],)).fetchone()
        if not asset or not species_match(topic["species"], asset["species"]):
            errors.append("missing or wrong-species asset")
            continue
        errors.extend(rights_errors(asset, publishable=not simulation))
        if asset["test_only"] and not simulation:
            errors.append("test asset cannot enter production")
        if not errors:
            try:
                probe(Path(asset["path"]))
            except ValueError as exc:
                errors.append(str(exc))
        clips.append(asset)
    cfg = settings()["render"]
    duration = sum(float(s["duration_s"]) for s in plan["segments"])
    min_duration = plan_min_duration(plan, cfg)
    if not simulation and not min_duration <= duration <= cfg["max_duration_s"]:
        errors.append("duration outside approved production range")
    if errors:
        raise ValueError("; ".join(sorted(set(errors))))
    width, height, fps = cfg["width"], cfg["height"], cfg["fps"]
    output_dir = ROOT / "output" / plan_id
    output_dir.mkdir(parents=True, exist_ok=True)
    if not simulation:
        narration = synthesize(" ".join(s["text"] for s in plan["segments"]),
                               output_dir / "narration.wav")
    assert narration is not None
    audio = probe_audio(narration)
    if not audio:
        raise ValueError("missing or corrupt narration")
    out = output_dir / "master.mp4"
    part = output_dir / "master.part.mp4"
    args = []
    filters = []
    for i, (shot, asset) in enumerate(zip(plan["segments"], clips)):
        args += ["-ss", str(shot["start_s"]), "-t", str(shot["duration_s"]),
                 "-i", asset["path"]]
        focus = max(0.0, min(1.0, float(shot.get("focus_x", 0.5))))
        filters.append(
            f"[{i}:v]fps={fps},scale={width}:{height}:force_original_aspect_ratio=increase,"
            f"crop={width}:{height}:x=(iw-{width})*{focus:.3f}:y=(ih-{height})/2,"
            f"setsar=1,trim=duration={float(shot['duration_s']):.3f},setpts=PTS-STARTPTS[v{i}]")
    captions = []
    gain_db = 0.0
    if not simulation:
        captions = align(narration, " ".join(s["text"] for s in plan["segments"]),
                         output_dir / "alignment")
        write_srt(captions, output_dir / "captions.srt")
        gain_db = narration_gain(narration)
    args += ["-i", str(narration)]
    filters.append("".join(f"[v{i}]" for i in range(len(clips))) +
                   f"concat=n={len(clips)}:v=1:a=0[raw]")
    if captions:
        subtitle_path = str(output_dir / "captions.srt").replace("\\", "\\\\").replace(":", "\\:").replace("'", "\\'")
        filters.append(f"[raw]subtitles='{subtitle_path}':force_style='Alignment=2,MarginV=55,FontSize=12,Outline=2'[v]")
    else:
        filters.append("[raw]null[v]")
    loudness_chain = (f",volume={gain_db:.2f}dB,alimiter=limit=0.891:level=false"
                      if not simulation else "")
    filters.append(f"[{len(clips)}:a]atrim=duration={duration:.3f},"
                   f"apad=whole_dur={duration:.3f},asetpts=PTS-STARTPTS{loudness_chain}[a]")
    args += ["-filter_complex", ";".join(filters), "-map", "[v]", "-map", "[a]",
             "-c:v", _encoder(), "-b:v", "8M", "-pix_fmt", "yuv420p",
             "-c:a", "aac", "-b:a", "160k", "-t", f"{duration:.3f}",
             "-movflags", "+faststart", str(part)]
    try:
        _ffmpeg(args)
        result = probe(part)
        if result["width"] != width or result["height"] != height or abs(result["duration"] - duration) > 0.2:
            raise RuntimeError("render failed dimension or duration validation")
        os.replace(part, out)
    finally:
        part.unlink(missing_ok=True)
    evidence_snapshot = {
        "facts": [{"id": f["id"], "status": f["status"],
                   "sha256": digest_statements(f["statement"] + f["excerpt"])}
                  for f in (conn.execute("SELECT * FROM facts WHERE id=?",
                                         (fid,)).fetchone()
                            for fid in {fid for s in plan["segments"]
                                        for fid in s["fact_ids"]})],
        "assets": [{"id": a["id"], "sha256": a["sha256"], "license": a["license_type"],
                    "approved": a["approved"]} for a in clips]}
    manifest = {"brand": "Naminal Hub", "plan_id": plan_id, "revision": row["revision"],
                "plan_hash": row["hash"], "video_hash": digest(out),
                "narration_hash": digest(narration),
                "evidence_snapshot": evidence_snapshot, "assets": [
                    {"id": a["id"], "sha256": a["sha256"], "creator": a["creator"],
                     "license": a["license_type"], "evidence": a["evidence"],
                     "attribution": a["attribution"]} for a in clips],
                "facts": list({fid for s in plan["segments"] for fid in s["fact_ids"]}),
                "duration": result["duration"], "test_only": simulation,
                "runtime_exception": plan.get("runtime_exception"),
                "voice": settings()["voice"] if not simulation else {"backend": "test_only"}}
    audio_duration = float(subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=noprint_wrappers=1:nokey=1", str(narration)],
        capture_output=True, text=True, check=True, timeout=60).stdout.strip())
    audio_timing = simulation or audio_timing_ok(duration, audio_duration)
    if not simulation:
        black = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(out),
                                "-vf", "blackdetect=d=0.5:pix_th=0.10",
                                "-an", "-f", "null", "-"], capture_output=True,
                               text=True, timeout=300)
        visual_ok = black.returncode == 0 and "black_start:" not in black.stderr
    else:
        visual_ok = False
    try:
        loudness = None if simulation else loudness_lufs(out)
        loudness_ok = simulation or abs(
            loudness - cfg["loudness_target"]) <= cfg["loudness_tolerance"]
    except RuntimeError:
        loudness, loudness_ok = None, False
    qc = {"ok": not simulation and visual_ok and audio_timing and loudness_ok,
          "voice": settings()["voice"] if not simulation else None,
          "loudness_lufs": loudness, "loudness_gain_db": None if simulation else gain_db,
          "checks": {"format": True, "rights": not simulation,
                     "claims": not errors, "narration": bool(audio),
                     "audio_timing": audio_timing, "no_black_intervals": visual_ok,
                     "loudness": loudness_ok, "captions": bool(captions)},
          "limitations": ["visual species and semantic citations require operator review",
                          "subject crop accuracy needs operator review"]}
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    conn.execute("UPDATE plans SET status=?,video_path=?,video_hash=?,qc=? WHERE id=?",
                 ("READY_FOR_REVIEW" if qc["ok"] else "QC_FAILED", str(out),
                  manifest["video_hash"], json.dumps(qc), plan_id))
    return {"video": str(out), "manifest": manifest, "qc": qc}


def probe_audio(path: Path) -> bool:
    if not path.is_file():
        return False
    result = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "a",
                             "-show_entries", "stream=codec_type", "-of", "json", str(path)],
                            capture_output=True, text=True, timeout=60)
    return result.returncode == 0 and bool(json.loads(result.stdout).get("streams"))
